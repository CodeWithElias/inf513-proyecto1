
CREATE TABLE rol (
    id_rol        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL UNIQUE,
    descripcion   VARCHAR(255),
    activo        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE unidad_universitaria (
    id_unidad         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(150) NOT NULL,
    tipo              VARCHAR(50),
    activo            BOOLEAN NOT NULL DEFAULT TRUE,
    id_unidad_padre   INTEGER,   -- asociación reflexiva 0..1 / 0..*
    CONSTRAINT fk_unidad_padre FOREIGN KEY (id_unidad_padre)
        REFERENCES unidad_universitaria (id_unidad) ON DELETE SET NULL
);

CREATE TABLE empresa_anunciante (
    id_empresa            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social          VARCHAR(200) NOT NULL,
    nit                   VARCHAR(30)  NOT NULL UNIQUE,
    nombre_comercial      VARCHAR(200),
    direccion_facturacion VARCHAR(255),
    email_facturacion     VARCHAR(150),
    telefono              VARCHAR(30),
    activo                BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE visitante (
    id_visitante    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(150) NOT NULL,
    email           VARCHAR(150),
    telefono        VARCHAR(30),
    fecha_registro  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE servicio_publicitario (
    id_servicio   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(150) NOT NULL,
    tipo          VARCHAR(50),
    descripcion   VARCHAR(500),
    activo        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE paquete (
    id_paquete    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(150) NOT NULL,
    descripcion   VARCHAR(500),
    descuento     NUMERIC(5,2) NOT NULL DEFAULT 0,
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    precio_total  NUMERIC(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE canal_difusion (
    id_canal    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(50),
    nombre      VARCHAR(150) NOT NULL,
    fecha_alta  DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_baja  DATE,
    activo      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE plataforma (
    id_plataforma  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE termino_monitoreo (
    id_termino  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termino     VARCHAR(200) NOT NULL,
    tipo        VARCHAR(50),
    activo      BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================================
-- 2. USUARIO Y ESPECIALIZACIÓN (representante)
-- =====================================================================

CREATE TABLE usuario (
    id_usuario       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR(200) NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE,
    telefono         VARCHAR(30),
    password_hash    VARCHAR(255) NOT NULL,
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso    TIMESTAMP,
    id_rol           INTEGER NOT NULL,   -- usuario 0..* - 1 rol
    id_unidad        INTEGER,            -- usuario 0..1 - unidad 0..*
    CONSTRAINT fk_usuario_rol    FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_universitaria (id_unidad) ON DELETE SET NULL
);

-- representante ES UN usuario (generalización) y pertenece a una empresa
-- (composición empresa_anunciante 1 -> 1..* representante)
CREATE TABLE representante (
    id_usuario  INTEGER PRIMARY KEY,
    ci          VARCHAR(20) NOT NULL UNIQUE,
    cargo       VARCHAR(100),
    id_empresa  INTEGER NOT NULL,
    CONSTRAINT fk_representante_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_representante_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa_anunciante (id_empresa) ON DELETE CASCADE
);

-- =====================================================================
-- 3. PROFORMAS, CAMPAÑAS Y TARIFAS
-- =====================================================================

CREATE TABLE proforma (
    id_proforma    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_proforma   VARCHAR(30) NOT NULL UNIQUE,
    fecha_emision  DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_validez  DATE,
    descuento      NUMERIC(12,2) NOT NULL DEFAULT 0,
    total          NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado         VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    subtotal       NUMERIC(12,2) NOT NULL DEFAULT 0,
    id_empresa     INTEGER,   -- empresa 0..1 "realiza" proforma 0..*
    id_visitante   INTEGER,   -- visitante 0..1 "realiza" proforma 0..*
    CONSTRAINT fk_proforma_empresa   FOREIGN KEY (id_empresa)
        REFERENCES empresa_anunciante (id_empresa),
    CONSTRAINT fk_proforma_visitante FOREIGN KEY (id_visitante)
        REFERENCES visitante (id_visitante)
);

-- proforma 1 - 0..1 campania
CREATE TABLE campania (
    id_campania  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(200) NOT NULL,
    fecha_inicio DATE,
    fecha_fin    DATE,
    estado       VARCHAR(30) NOT NULL DEFAULT 'activa',
    id_proforma  INTEGER NOT NULL UNIQUE,
    CONSTRAINT fk_campania_proforma FOREIGN KEY (id_proforma)
        REFERENCES proforma (id_proforma)
);

CREATE TABLE tarifa (
    id_tarifa      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto          NUMERIC(12,2) NOT NULL,
    unidad_cobro   VARCHAR(50),
    vigente_desde  DATE,
    vigente_hasta  DATE,
    duracion_seg   INTEGER,
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    id_servicio    INTEGER NOT NULL,   -- servicio 1 - tarifa 0..*
    id_unidad      INTEGER,            -- unidad 0..1 - tarifa 0..*
    CONSTRAINT fk_tarifa_servicio FOREIGN KEY (id_servicio)
        REFERENCES servicio_publicitario (id_servicio),
    CONSTRAINT fk_tarifa_unidad   FOREIGN KEY (id_unidad)
        REFERENCES unidad_universitaria (id_unidad) ON DELETE SET NULL
);

-- Clase de asociación paquete 0..* <-> tarifa 1..*
CREATE TABLE paquete_item (
    id_paquete  INTEGER NOT NULL,
    id_tarifa   INTEGER NOT NULL,
    cantidad    INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (id_paquete, id_tarifa),
    CONSTRAINT fk_paquete_item_paquete FOREIGN KEY (id_paquete)
        REFERENCES paquete (id_paquete) ON DELETE CASCADE,
    CONSTRAINT fk_paquete_item_tarifa  FOREIGN KEY (id_tarifa)
        REFERENCES tarifa (id_tarifa)
);

-- composición proforma 1 -> 1..* detalle_proforma
CREATE TABLE detalle_proforma (
    id_detalle       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad         INTEGER NOT NULL DEFAULT 1,
    precio_unitario  NUMERIC(12,2) NOT NULL,
    subtotal         NUMERIC(12,2) NOT NULL,
    frecuencia       VARCHAR(50),
    id_proforma      INTEGER NOT NULL,
    id_tarifa        INTEGER,   -- tarifa 0..1
    id_paquete       INTEGER,   -- paquete 0..1
    CONSTRAINT fk_detalle_proforma FOREIGN KEY (id_proforma)
        REFERENCES proforma (id_proforma) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_tarifa   FOREIGN KEY (id_tarifa)
        REFERENCES tarifa (id_tarifa),
    CONSTRAINT fk_detalle_paquete  FOREIGN KEY (id_paquete)
        REFERENCES paquete (id_paquete)
);

-- =====================================================================
-- 4. MATERIAL PUBLICITARIO
-- =====================================================================

-- composición campania 1 -> 0..* material_publicitario
CREATE TABLE material_publicitario (
    id_material        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               VARCHAR(50),
    nombre_archivo     VARCHAR(255) NOT NULL,
    url_archivo        VARCHAR(500),
    formato            VARCHAR(30),
    tamano_bytes       BIGINT,
    duracion_seg       INTEGER,
    texto_publicacion  TEXT,
    version            INTEGER NOT NULL DEFAULT 1,
    estado             VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    fecha_carga        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_campania        INTEGER NOT NULL,
    id_usuario         INTEGER,   -- usuario 1 - material 0..*
    CONSTRAINT fk_material_campania FOREIGN KEY (id_campania)
        REFERENCES campania (id_campania) ON DELETE CASCADE,
    CONSTRAINT fk_material_usuario  FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
);

-- composición material 1 -> 0..* revision_material
CREATE TABLE revision_material (
    id_revision    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado      VARCHAR(50),
    observaciones  TEXT,
    id_material    INTEGER NOT NULL,
    id_usuario     INTEGER,   -- usuario 1 - revision 0..*
    CONSTRAINT fk_revision_material FOREIGN KEY (id_material)
        REFERENCES material_publicitario (id_material) ON DELETE CASCADE,
    CONSTRAINT fk_revision_usuario  FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
);

-- =====================================================================
-- 5. CANALES, REDES SOCIALES Y ESPACIOS
-- =====================================================================

-- red_social ES UN canal_difusion (generalización)
CREATE TABLE red_social (
    id_canal       INTEGER PRIMARY KEY,
    url            VARCHAR(500) NOT NULL,
    id_plataforma  INTEGER NOT NULL,   -- plataforma 1 - red_social 0..*
    id_usuario     INTEGER,            -- usuario 1 - red_social 0..*
    id_unidad      INTEGER,            -- unidad 1 (composición) - red_social 0..*
    CONSTRAINT fk_red_social_canal      FOREIGN KEY (id_canal)
        REFERENCES canal_difusion (id_canal) ON DELETE CASCADE,
    CONSTRAINT fk_red_social_plataforma FOREIGN KEY (id_plataforma)
        REFERENCES plataforma (id_plataforma),
    CONSTRAINT fk_red_social_usuario    FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_red_social_unidad     FOREIGN KEY (id_unidad)
        REFERENCES unidad_universitaria (id_unidad) ON DELETE CASCADE
);

-- composición red_social 1 -> 0..* seguidores_red
CREATE TABLE seguidores_red (
    id_seguidores  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seguidores     INTEGER NOT NULL DEFAULT 0,
    fecha          DATE NOT NULL DEFAULT CURRENT_DATE,
    id_canal       INTEGER NOT NULL,
    CONSTRAINT fk_seguidores_red_social FOREIGN KEY (id_canal)
        REFERENCES red_social (id_canal) ON DELETE CASCADE
);

-- composición canal_difusion 1 -> 0..* espacio_publicitario
CREATE TABLE espacio_publicitario (
    id_espacio   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        DATE NOT NULL,
    hora_inicio  TIME NOT NULL,
    hora_fin     TIME NOT NULL,
    estado       VARCHAR(30) NOT NULL DEFAULT 'disponible',
    id_canal     INTEGER NOT NULL,
    CONSTRAINT fk_espacio_canal FOREIGN KEY (id_canal)
        REFERENCES canal_difusion (id_canal) ON DELETE CASCADE
);

-- =====================================================================
-- 6. PROGRAMACIÓN DE PAUTAS Y MÉTRICAS
-- =====================================================================

CREATE TABLE programacion_pauta (
    id_programacion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              VARCHAR(30) NOT NULL DEFAULT 'programada',
    url_publicacion     VARCHAR(500),
    fecha_programacion  TIMESTAMP,
    id_detalle          INTEGER NOT NULL,        -- detalle 1 - programacion 0..*
    id_material         INTEGER NOT NULL,        -- material 1 - programacion 0..*
    id_espacio          INTEGER UNIQUE,          -- espacio 1 - programacion 0..1
    id_usuario          INTEGER,                 -- usuario 1 - programacion 0..*
    CONSTRAINT fk_programacion_detalle  FOREIGN KEY (id_detalle)
        REFERENCES detalle_proforma (id_detalle),
    CONSTRAINT fk_programacion_material FOREIGN KEY (id_material)
        REFERENCES material_publicitario (id_material),
    CONSTRAINT fk_programacion_espacio  FOREIGN KEY (id_espacio)
        REFERENCES espacio_publicitario (id_espacio),
    CONSTRAINT fk_programacion_usuario  FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
);

-- composición programacion_pauta 1 -> 0..* metrica_publicacion
CREATE TABLE metrica_publicacion (
    id_metrica       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_medicion   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    alcance          INTEGER NOT NULL DEFAULT 0,
    impresiones      INTEGER NOT NULL DEFAULT 0,
    interacciones    INTEGER NOT NULL DEFAULT 0,
    clics            INTEGER NOT NULL DEFAULT 0,
    compartidos      INTEGER NOT NULL DEFAULT 0,
    id_programacion  INTEGER NOT NULL,
    CONSTRAINT fk_metrica_programacion FOREIGN KEY (id_programacion)
        REFERENCES programacion_pauta (id_programacion) ON DELETE CASCADE
);

-- =====================================================================
-- 7. MONITOREO / SCRAPING Y NOTIFICACIONES
-- =====================================================================

CREATE TABLE pagina_no_autorizada (
    id_pagina       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url             VARCHAR(500) NOT NULL,
    nombre_pagina   VARCHAR(200),
    estado          VARCHAR(30) NOT NULL DEFAULT 'detectada',
    fecha_revision  TIMESTAMP,
    id_plataforma   INTEGER NOT NULL,   -- plataforma 1 - pagina 0..*
    id_usuario      INTEGER,            -- usuario 0..1 - pagina 0..*
    CONSTRAINT fk_pagina_plataforma FOREIGN KEY (id_plataforma)
        REFERENCES plataforma (id_plataforma),
    CONSTRAINT fk_pagina_usuario    FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

-- plataforma 1 - ejecucion_scraping 0..*
CREATE TABLE ejecucion_scraping (
    id_ejecucion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin      TIMESTAMP,
    estado         VARCHAR(30) NOT NULL DEFAULT 'en_proceso',
    mensaje_error  TEXT,
    id_plataforma  INTEGER NOT NULL,
    CONSTRAINT fk_ejecucion_plataforma FOREIGN KEY (id_plataforma)
        REFERENCES plataforma (id_plataforma)
);

-- composición ejecucion_scraping 1 -> 0..* deteccion_pagina
-- pagina_no_autorizada 1 - 1..* deteccion_pagina ; termino 1 - 0..* deteccion
CREATE TABLE deteccion_pagina (
    id_deteccion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidencia        TEXT,
    fecha_deteccion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_pagina        INTEGER NOT NULL,
    id_termino       INTEGER,
    id_ejecucion     INTEGER NOT NULL,
    CONSTRAINT fk_deteccion_pagina    FOREIGN KEY (id_pagina)
        REFERENCES pagina_no_autorizada (id_pagina) ON DELETE CASCADE,
    CONSTRAINT fk_deteccion_termino   FOREIGN KEY (id_termino)
        REFERENCES termino_monitoreo (id_termino) ON DELETE SET NULL,
    CONSTRAINT fk_deteccion_ejecucion FOREIGN KEY (id_ejecucion)
        REFERENCES ejecucion_scraping (id_ejecucion) ON DELETE CASCADE
);

CREATE TABLE notificacion (
    id_notificacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medio            VARCHAR(30),
    titulo           VARCHAR(200) NOT NULL,
    mensaje          TEXT,
    fecha_envio      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leida            BOOLEAN NOT NULL DEFAULT FALSE,
    id_usuario       INTEGER NOT NULL,   -- usuario 1 - notificacion 0..*
    id_deteccion     INTEGER,            -- deteccion 0..1 - notificacion 0..*
    id_programacion  INTEGER,            -- programacion 0..1 - notificacion 0..*
    CONSTRAINT fk_notificacion_usuario      FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_notificacion_deteccion    FOREIGN KEY (id_deteccion)
        REFERENCES deteccion_pagina (id_deteccion) ON DELETE SET NULL,
    CONSTRAINT fk_notificacion_programacion FOREIGN KEY (id_programacion)
        REFERENCES programacion_pauta (id_programacion) ON DELETE SET NULL
);

